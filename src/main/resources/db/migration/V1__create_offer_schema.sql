CREATE TABLE offers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id VARCHAR(255),
    title VARCHAR(255) NOT NULL,
    company_name VARCHAR(255) NOT NULL,
    location VARCHAR(255),
    experience_level VARCHAR(100),
    employment_type VARCHAR(100),
    work_mode VARCHAR(50),
    working_time VARCHAR(50),
    salary_min NUMERIC(19, 2),
    salary_max NUMERIC(19, 2),
    salary_unit VARCHAR(255),
    currency VARCHAR(3),
    source VARCHAR(100),
    url VARCHAR(1000),
    language VARCHAR(255),
    category VARCHAR(255),
    published_at TIMESTAMP(6),
    expired_at TIMESTAMP(6),
    open_to_hire_ukrainians BOOLEAN,
    version BIGINT,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6)
);

CREATE INDEX idx_job_offer_external_id ON offers (external_id);
CREATE INDEX idx_job_offer_title_company ON offers (title, company_name);
CREATE INDEX idx_job_offer_location ON offers (location);

CREATE TABLE technologies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    level INTEGER
);

CREATE TABLE job_offer_technologies (
    job_offer_id BIGINT NOT NULL,
    technology_id BIGINT NOT NULL,
    PRIMARY KEY (job_offer_id, technology_id),
    CONSTRAINT fk_job_offer_technologies_offer
        FOREIGN KEY (job_offer_id) REFERENCES offers (id),
    CONSTRAINT fk_job_offer_technologies_technology
        FOREIGN KEY (technology_id) REFERENCES technologies (id)
);

CREATE INDEX idx_job_offer_technologies_technology
    ON job_offer_technologies (technology_id);
