CREATE TABLE synchronization_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cycle_id UUID NOT NULL,
    source VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL,
    started_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP(6) WITH TIME ZONE,
    fetched_offers INTEGER,
    persisted_offers INTEGER,
    error_type VARCHAR(255),
    error_message VARCHAR(2000),
    CONSTRAINT chk_synchronization_run_status
        CHECK (status IN ('RUNNING', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT chk_synchronization_run_counts
        CHECK (
            (fetched_offers IS NULL OR fetched_offers >= 0)
            AND (persisted_offers IS NULL OR persisted_offers >= 0)
            AND (fetched_offers IS NULL OR persisted_offers IS NULL OR persisted_offers <= fetched_offers)
        )
);

CREATE INDEX idx_synchronization_runs_cycle_id
    ON synchronization_runs (cycle_id);

CREATE INDEX idx_synchronization_runs_source_started_at
    ON synchronization_runs (source, started_at);
